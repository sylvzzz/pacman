    def draw_char(self, char) -> None:
        for row in char:
            for bit in row:
                print(bit, end="")
            print()

    @property
    def bits(self) -> list:
        return self.chars.get(self.char, "")

    def write(self, chars) -> None:
        try:
            for ch in chars:
                self.draw_char(self.char[ch])
        except:
             print("This character is invalid...")


